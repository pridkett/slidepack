// Package envelope writes and reads the HTML container of a packed
// presentation.
//
// The container is deliberately boring: fixed marker comment, one <script>
// holding the JSON manifest, one <script> holding the single base64 payload,
// one <script> holding the runtime. Locating those three elements needs a
// substring search, not an HTML parser, which is what lets `slidepack unpack`
// identify a slidepack file without interpreting arbitrary markup.
package envelope

import (
	"bufio"
	"bytes"
	"encoding/base64"
	"errors"
	"fmt"
	"html"
	"io"
	"strings"

	"github.com/pwagstro/slidepack/internal/manifest"
	"github.com/pwagstro/slidepack/internal/runtime"
)

// Marker is the sentinel comment that identifies a packed presentation.
const Marker = "<!-- SLIDEPACK FORMAT 1 -->"

// Element IDs. These are part of the format contract; see docs/format-v1.md.
const (
	ManifestID = "slidepack-manifest"
	PayloadID  = "slidepack-payload"
	RuntimeID  = "slidepack-runtime"
	StatusID   = "slidepack-status"
	StyleID    = "slidepack-bootstrap-style"
)

// WriteOptions configures the document that Write produces.
type WriteOptions struct {
	// Manifest is serialised into the manifest element. Its payload digest and
	// sizes must already be filled in.
	Manifest *manifest.Manifest
	// Title becomes the outer document's <title>, so that the browser tab is
	// correct before any JavaScript runs. Usually the presentation's own title.
	Title string
	// Payload is the raw gzip stream; Write base64-encodes it on the fly.
	Payload io.Reader
}

// Write streams a complete packed presentation to w.
//
// The payload is encoded straight from the reader into the writer, so the
// encoder never holds more than a few kilobytes regardless of how large the
// presentation is.
func Write(w io.Writer, opts WriteOptions) error {
	if err := runtime.Check(); err != nil {
		return err
	}
	mjson, err := opts.Manifest.Marshal()
	if err != nil {
		return fmt.Errorf("serialising manifest: %w", err)
	}
	// Go's JSON encoder escapes <, > and & as <, > and & by
	// default, so a file named "</script>.png" cannot terminate the element.
	if bytes.Contains(bytes.ToLower(mjson), []byte("</script")) {
		return errors.New("internal error: manifest JSON contains a script-terminating sequence")
	}

	bw := bufio.NewWriterSize(w, 1<<16)

	title := strings.TrimSpace(opts.Title)
	if title == "" {
		title = "Presentation"
	}

	if _, err := io.WriteString(bw, header(title)); err != nil {
		return err
	}
	if _, err := bw.Write(mjson); err != nil {
		return err
	}
	if _, err := io.WriteString(bw, betweenManifestAndPayload); err != nil {
		return err
	}

	enc := base64.NewEncoder(base64.StdEncoding, bw)
	if _, err := io.Copy(enc, opts.Payload); err != nil {
		return fmt.Errorf("encoding payload: %w", err)
	}
	if err := enc.Close(); err != nil {
		return fmt.Errorf("finishing payload: %w", err)
	}

	if _, err := io.WriteString(bw, footer()); err != nil {
		return err
	}
	return bw.Flush()
}

func header(title string) string {
	var b strings.Builder
	b.WriteString("<!doctype html>\n")
	b.WriteString(`<html lang="en">` + "\n")
	b.WriteString("<head>\n")
	b.WriteString(`<meta charset="utf-8">` + "\n")
	b.WriteString(`<meta name="viewport" content="width=device-width, initial-scale=1, viewport-fit=cover">` + "\n")
	b.WriteString(`<meta name="generator" content="slidepack format 1">` + "\n")
	b.WriteString("<title>" + html.EscapeString(title) + "</title>\n")
	b.WriteString(Marker + "\n")
	b.WriteString(generatedNotice)
	b.WriteString(`<style id="` + StyleID + `">` + "\n")
	b.WriteString(runtime.CSS())
	b.WriteString("</style>\n")
	b.WriteString("</head>\n")
	b.WriteString("<body>\n")
	b.WriteString(statusBlock)
	b.WriteString(`<script id="` + ManifestID + `" type="application/json">` + "\n")
	return b.String()
}

const generatedNotice = `<!--
  Generated by slidepack. This file is a compiled distribution artifact.

  The presentation source is the single base64 payload below; editing this
  document by hand will not survive the next pack, and reading the payload is
  not a useful way to inspect the presentation. Instead:

      slidepack unpack this-file.html -o ./presentation
      ... edit ./presentation ...
      slidepack pack ./presentation -o this-file.html

  Opening this file runs the JavaScript it contains. Only open presentations
  from sources you trust.
-->
`

const statusBlock = `<div id="` + StatusID + `">
<p class="slidepack-loading"><span class="slidepack-spinner"></span>Loading presentation&#8230;</p>
<noscript><style>.slidepack-loading{display:none}</style><div class="slidepack-panel"><p class="slidepack-title">This presentation needs JavaScript.</p><p class="slidepack-footnote">A slidepack presentation stores its slides, styles, images and fonts in a compressed archive inside this file, and expands that archive in the browser. Enable JavaScript for this page, or run <code>slidepack unpack</code> to recover the original source files.</p></div></noscript>
</div>
`

const betweenManifestAndPayload = `
</script>
<script id="` + PayloadID + `" type="application/octet-stream" data-format="tar" data-compression="gzip" data-encoding="base64">
`

func footer() string {
	var b strings.Builder
	b.WriteString("\n</script>\n")
	b.WriteString(`<script id="` + RuntimeID + `">` + "\n")
	b.WriteString(runtime.JS())
	b.WriteString("</script>\n")
	b.WriteString("</body>\n")
	b.WriteString("</html>\n")
	return b.String()
}

