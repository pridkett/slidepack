// Document is a parsed packed presentation.
type Document struct {
	// ManifestJSON is the raw text of the manifest element.
	ManifestJSON []byte
	// PayloadBase64 is the raw text of the payload element, whitespace trimmed.
	PayloadBase64 []byte
	// PayloadAttrs are the data-* attributes declared on the payload element.
	PayloadAttrs map[string]string
}

// ErrNotSlidepack means the file is not a packed slidepack presentation.
var ErrNotSlidepack = errors.New("not a slidepack presentation")

// Parse locates the manifest and payload elements in a packed document.
func Parse(doc []byte) (*Document, error) {
	if !bytes.Contains(doc, []byte(Marker)) {
		// The marker is checked first so that an ordinary HTML file produces a
		// clear "this is not a slidepack file" rather than a confusing report
		// about a missing element.
		return nil, fmt.Errorf("%w: the %s marker is absent", ErrNotSlidepack, Marker)
	}
	_, mbody, err := findScript(doc, ManifestID)
	if err != nil {
		return nil, err
	}
	ptag, pbody, err := findScript(doc, PayloadID)
	if err != nil {
		return nil, err
	}
	return &Document{
		ManifestJSON:  bytes.TrimSpace(mbody),
		PayloadBase64: bytes.TrimSpace(pbody),
		PayloadAttrs:  parseAttrs(ptag),
	}, nil
}

// findScript returns the opening tag and the body of the <script> element with
// the given id.
//
// The search anchors on the id attribute and then walks backwards to the
// element's "<script", which tolerates attribute reordering without needing a
// real parser. Both the manifest (JSON with < escaped) and the payload (base64)
// are guaranteed not to contain "</script", so the first one found ends the
// element.
func findScript(doc []byte, id string) (tag, body []byte, err error) {
	start := -1
	for _, form := range [][]byte{
		[]byte(`id="` + id + `"`),
		[]byte(`id='` + id + `'`),
		[]byte(`id=` + id),
	} {
		if i := bytes.Index(doc, form); i >= 0 {
			start = i
			break
		}
	}
	if start < 0 {
		return nil, nil, fmt.Errorf("%w: no element with id %q", ErrNotSlidepack, id)
	}
	open := bytes.LastIndex(doc[:start], []byte("<script"))
	if open < 0 {
		return nil, nil, fmt.Errorf("malformed envelope: id %q is not on a <script> element", id)
	}
	if bytes.Contains(doc[open:start], []byte(">")) {
		return nil, nil, fmt.Errorf("malformed envelope: id %q is not inside a <script> start tag", id)
	}
	gt := bytes.IndexByte(doc[start:], '>')
	if gt < 0 {
		return nil, nil, fmt.Errorf("malformed envelope: unterminated <script> start tag for id %q", id)
	}
	contentStart := start + gt + 1
	end := bytes.Index(doc[contentStart:], []byte("</script"))
	if end < 0 {
		return nil, nil, fmt.Errorf("malformed envelope: unterminated <script> element for id %q", id)
	}
	return doc[open:contentStart], doc[contentStart : contentStart+end], nil
}

// parseAttrs pulls name="value" pairs out of a start tag.
func parseAttrs(tag []byte) map[string]string {
	out := map[string]string{}
	s := string(tag)
	i := 0
	for i < len(s) {
		eq := strings.IndexByte(s[i:], '=')
		if eq < 0 {
			break
		}
		eq += i
		// Walk back to the start of the attribute name.
		j := eq
		for j > 0 && !isSpaceByte(s[j-1]) {
			j--
		}
		name := strings.TrimSpace(s[j:eq])
		rest := s[eq+1:]
		if len(rest) == 0 {
			break
		}
		var value string
		if rest[0] == '"' || rest[0] == '\'' {
			q := rest[0]
			k := strings.IndexByte(rest[1:], q)
			if k < 0 {
				break
			}
			value = rest[1 : 1+k]
			i = eq + 1 + 1 + k + 1
		} else {
			k := 0
			for k < len(rest) && !isSpaceByte(rest[k]) && rest[k] != '>' {
				k++
			}
			value = rest[:k]
			i = eq + 1 + k
		}
		if name != "" {
			out[name] = value
		}
	}
	return out
}

func isSpaceByte(c byte) bool {
	return c == ' ' || c == '\t' || c == '\n' || c == '\r' || c == '\f'
}
